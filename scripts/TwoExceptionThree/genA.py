"""Writes OddPerfect/TwoExceptionThreeAData.lean: the Pratt certificate of the large witness primes
and the walk over n = 11, 21, ..., 116271 checked by TwoExceptionThreeA.cover. Every entry is
first checked by an exact Python mirror of the Lean checker. Deterministic.
Usage: python3 -I genA.py OUT.lean"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from sympy import factorint, isprime
import pratt

HI = 116281
TH = 10 ** 4          # witnesses below TH use sqrtPrime, the others the Pratt certificate
CHUNK = 500


def phi3(t): return t * t + t + 1
def phi5(x): return x ** 4 + x ** 3 + x ** 2 + x + 1
def strip_one(g, z, fuel=200):
    while fuel > 0 and g > 1 and z % g == 0:
        z //= g; fuel -= 1
    return z
def cof(n, t):
    z = phi3(t)
    for g in (13, 61, n): z = strip_one(g, z)
    return z
def sqrt_prime(w):
    if w < 2: return False
    d = 2
    while d * d <= w:
        if w % d == 0: return False
        d += 1
    return True
def ok_entry(P, n, w):
    if 1 < w < n and n % w == 0: return True
    if n == 61: return True
    c = cof(n, w)
    return (phi5(n) % w == 0 and w not in (5, 61, n, 13) and
            (w % 3 == 1 or (c != 1 and c % 13 and c % 61 and c % n)) and
            (w in P or sqrt_prime(w)))

def witness(x):
    for t in sorted(factorint(phi5(x))):
        if t in (5, 61, x, 13): continue
        c = cof(x, t)
        if t % 3 == 1 or (c != 1 and c % 13 and c % 61 and c % x):
            return t
    raise ValueError(x)

def main():
    out = sys.argv[1]
    entries = []
    big = []
    for n in range(11, HI, 10):
        if n == 61: entries.append((n, 0)); continue
        f = factorint(n)
        if len(f) > 1 or max(f.values()) > 1:
            entries.append((n, min(f))); continue
        t = witness(n)
        assert isprime(t)
        if t >= TH: big.append(t)
        entries.append((n, t))
    chunks = [entries[i:i + CHUNK] for i in range(0, len(entries), CHUNK)]
    # one Pratt certificate per chunk: the union of the chains of its large witnesses
    certs = []
    for ch in chunks:
        cert, seen = [], set()
        for n, w in ch:
            if w >= TH and n % w != 0:
                for e in pratt.cert(w):
                    if e[0] not in seen:
                        seen.add(e[0]); cert.append(e)
        assert pratt.check(cert)
        P = set(e[0] for e in cert)
        assert all(ok_entry(P, n, w) for n, w in ch)
        certs.append(cert)
    L = []
    L.append('import OddPerfect.TwoExceptionThreeACheck')
    L.append('')
    L.append('/-!')
    L.append('# Data for the forcing step of branch A')
    L.append('')
    L.append('Generated by `scripts/TwoExceptionThree/genA.py`. The walk lists, for')
    L.append('`n = 11, 21, …, 116271`, a divisor of a composite `n` or a witness prime of a prime `n`, in')
    L.append('chunks of %d values; each chunk carries a Pratt certificate of its witnesses at least' % CHUNK)
    L.append('`%d`, and smaller witnesses pass trial division.' % TH)
    L.append('-/')
    L.append('')
    L.append('set_option Elab.async false')
    L.append('')
    L.append('namespace OddPerfect.TwoExceptionThreeA')
    bounds = []
    for i, ch in enumerate(chunks):
        lo = ch[0][0]; hi = ch[-1][0] + 10
        bounds.append((lo, hi))
        L.append('')
        L.append('/-- Pratt certificate of chunk %d. -/' % i)
        L.append('def cert%d : List (ℕ × ℕ × List ℕ) :=' % i)
        L.append('  [' + ',\n   '.join('(%d, %d, [%s])' % (p, a, ', '.join(map(str, fs)))
                                     for p, a, fs in certs[i]) + ']')
        L.append('')
        L.append('theorem cert%d_ok : Pratt.check cert%d = true := by decide +kernel' % (i, i))
        L.append('')
        L.append('/-- Walk entries of chunk %d. -/' % i)
        L.append('def walk%d : List (ℕ × ℕ) :=' % i)
        L.append('  [' + ', '.join('(%d, %d)' % e for e in ch) + ']')
        L.append('')
        L.append('theorem walk%d_ok : cover (cert%d.map Prod.fst) %d walk%d %d = true := by' % (i, i, lo, i, hi))
        L.append('  decide +kernel')
        L.append('')
        L.append('theorem good%d {x : ℕ} (hx : x.Prime) (h10 : x %% 10 = 1) (h61 : x ≠ 61)' % i)
        L.append('    (hlo : %d ≤ x) (hhi : x < %d) : Good x :=' % (lo, hi))
        L.append('  cover_sound (fun p hp => by')
        L.append('    obtain ⟨e, he, rfl⟩ := List.mem_map.mp hp')
        L.append('    exact Pratt.check_sound cert%d_ok e he) walk%d %d walk%d_ok x hlo hhi (by omega) hx h61' % (i, i, lo, i))
    # the table of integer square roots for the values 13^a 61^b < 10^20
    from math import isqrt
    tab = []
    for a in range(19):
        for b in range(12):
            z = 13 ** a * 61 ** b
            r = isqrt(4 * z - 3) if z < 10 ** 20 else 0
            if z < 10 ** 20:
                assert (r * r < 4 * z - 3 < (r + 1) ** 2) or (r * r == 4 * z - 3 and r < 21)
            tab.append(r)
    assert 13 ** 19 > 10 ** 20 and 61 ** 12 > 10 ** 20
    L.append('')
    L.append('/-- Integer square roots of `4 · 13^a 61^b - 3` for `13^a 61^b < 10^20`, at index `12 a + b`. -/')
    L.append('def rootTab : List ℕ := [' + ', '.join(map(str, tab)) + ']')
    L.append('')
    L.append('/-- No value `13^a 61^b < 10^20` equals `t^2 + t + 1` with `t ≥ 10`. -/')
    L.append('def tabOK : Bool :=')
    L.append('  (List.range 19).all fun a => (List.range 12).all fun b =>')
    L.append('    decide (10 ^ 20 ≤ 13 ^ a * 61 ^ b) ||')
    L.append('    (rootTab.getD (12 * a + b) 0 * rootTab.getD (12 * a + b) 0 < 4 * (13 ^ a * 61 ^ b) - 3 &&')
    L.append('      4 * (13 ^ a * 61 ^ b) - 3 < (rootTab.getD (12 * a + b) 0 + 1) * (rootTab.getD (12 * a + b) 0 + 1)) ||')
    L.append('    (rootTab.getD (12 * a + b) 0 * rootTab.getD (12 * a + b) 0 == 4 * (13 ^ a * 61 ^ b) - 3 &&')
    L.append('      rootTab.getD (12 * a + b) 0 < 21)')
    L.append('')
    L.append('theorem tabOK_true : tabOK = true := by decide +kernel')
    L.append('')
    L.append('/-- Every prime `x < 116281` with `x % 10 = 1` and `x ≠ 61` has a witness. -/')
    L.append('theorem good_of_lt {x : ℕ} (hx : x.Prime) (h10 : x % 10 = 1) (h61 : x ≠ 61)')
    L.append('    (h11 : 11 ≤ x) (hlt : x < %d) : Good x := by' % HI)
    for i, (lo, hi) in enumerate(bounds):
        if i < len(bounds) - 1:
            L.append('  by_cases c%d : x < %d' % (i, hi))
            L.append('  · exact good%d hx h10 h61 (by omega) c%d' % (i, i))
        else:
            L.append('  exact good%d hx h10 h61 (by omega) hlt' % i)
    L.append('')
    L.append('end OddPerfect.TwoExceptionThreeA')
    L.append('')
    for i in range(len(chunks)):
        L.append('#print axioms OddPerfect.TwoExceptionThreeA.cert%d_ok' % i)
        L.append('#print axioms OddPerfect.TwoExceptionThreeA.walk%d_ok' % i)
        L.append('#print axioms OddPerfect.TwoExceptionThreeA.good%d' % i)
    L.append('#print axioms OddPerfect.TwoExceptionThreeA.tabOK_true')
    L.append('#print axioms OddPerfect.TwoExceptionThreeA.good_of_lt')
    open(out, 'w').write('\n'.join(L) + '\n')
    print('entries', len(entries), 'big witnesses', len(big), 'pratt entries',
          sum(len(c) for c in certs), 'max chunk cert', max(len(c) for c in certs), 'chunks', len(chunks))

if __name__ == '__main__':
    main()
