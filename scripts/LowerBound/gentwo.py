# Untrusted helper script for the OddPerfect Lean library.
# Writes the modules OddPerfect/LowerBoundTwo*.lean: a size lower bound 10^B for odd perfect
# numbers by the factor chain method, checked by the checker of OddPerfect/LowerBound.lean.
# For each root prime p0 (with the smaller roots excluded) it runs the search of gen.py with
# fresh caches, flattens the tree, collects the Pratt data of every forced prime (emit.py),
# and writes: a data module with the prime table, table check modules, tree modules (the
# children of the first split of each root, checked in groups) and a final module.
# Used by: OddPerfect/LowerBoundTwo*.lean.
# Run: python3 -I gentwo.py B hints.json outdir plan   (the library used
#      python3 -I gentwo.py 150 two_hints.json out "T:2 R:3,5,7,11 G:3")
#   plan: T:<number of table check modules>, R:<roots>, G:<number of tree modules>.
#   hints.json: {"sig": {"p,a": [secs, {q: e}]}, "split": {composite: factor}}; with a sixth
#   argument record, the script also writes outdir/hints.json with the hints the search read.
# Requires: Python 3, sympy (1.14.0 was used). Running time: about 15 CPU minutes for B = 150.
# Untrusted: every result is checked again by the Lean kernel.
# Paths: sibling helper files are found next to this script.
# License: GPL 3, same as the repository.

import sys as _s, os as _o; _s.path.insert(0, _o.path.dirname(_o.path.abspath(__file__)))
import sys, os, json, atexit, math
import pftwo
sys.modules['pf'] = pftwo
os.environ['SPLIT'] = '1'
import gen, emit, nt, mktail
from sympy import isprime
atexit.unregister(gen._save_sig)
atexit.unregister(nt._save)
nt.pf = pftwo

CHUNK = 400      # instructions per definition
TCH = 127        # table entries per definition
PART = int(os.environ.get('GENTWO_PART', '2000'))  # instructions per tree check (unless unsplittable)


def check_hints(h):
    sig = {}
    for k, v in h['sig'].items():
        p, a = map(int, k.split(','))
        g = gen.geom(p, a)
        fs = {int(q): int(e) for q, e in v[1].items()}
        for q, e in fs.items():
            assert isprime(q) and g % q ** e == 0, (k, q)
        sig[(p, a)] = (int(v[0]), fs)
    split = {}
    for k, v in h['split'].items():
        k, v = int(k), int(v)
        assert 1 < v < k and k % v == 0
        split[k] = v
    return sig, split


def search(p0, excl, sig, record):
    gen._sig.clear(); gen._sig.update(sig)
    pftwo._cache.clear(); nt._fcache.clear(); nt._pratt.clear()
    gen.STATS['nodes'] = 0; gen.STATS['fail'] = 0; del gen.FAILS[:]
    orig = gen.sig_factors
    if record is not None:
        def rec(p, a, secs=20):
            key = (p, a)
            if key in sig and gen._sig.get(key) is sig[key] and sig[key][0] >= secs:
                record.add(key)
            return orig(p, a, secs)
        gen.sig_factors = rec
    st = gen.St(); st.lo[p0] = 1; st.nd = set(excl)
    t = gen.solve(st)
    gen.sig_factors = orig
    assert t is not None, ('root does not close', p0, gen.FAILS[:3])
    return t


def fact(f):
    return '.nd %d' % f[1] if f[0] == 'nd' else '.%s %d %d' % f


def lst(xs): return '[' + ', '.join(xs) + ']'


def defs_list(name, ins, doc):
    """Instruction list split into definitions of CHUNK instructions; returns (text, expr)."""
    out, names = [], []
    for i in range(0, len(ins), CHUNK):
        nm = '%s_%d' % (name, i // CHUNK); names.append(nm)
        out.append('/-- %s, part %d. -/\ndef %s : List Ins := [\n  %s]\n'
                   % (doc, i // CHUNK, nm, ',\n  '.join(ins[i:i + CHUNK])))
    return '\n'.join(out), ' ++ '.join(names)


HEAD = '''import %s

/-!
# %s

%s
-/

namespace OddPerfect.LowerBoundTwo

open OddPerfect.LowerBound

-- Check the theorems of this file one after another: in parallel the kernel checks of the
-- large `decide` proofs raise the peak memory above the budget of the library.
set_option Elab.async false
'''
DOC = ('Part of a kernel checked lower bound `10 ^ %d` for odd perfect numbers by the factor\n'
       'chain method, with the checker `run` of `OddPerfect.LowerBound`. The method and bounds of\n'
       'this size are known: Brent, Cohen and te Riele (1991) reached `10 ^ 300` and Ochem and Rao\n'
       '(2012) reached `10 ^ 1500`. The data are generated by `scripts/LowerBound/gentwo.py`.')


def module(imports, title, body, axioms):
    t = HEAD % ('\nimport '.join(imports), title, DOC % B) + '\n' + body
    t += '\nend OddPerfect.LowerBoundTwo\n'
    if axioms: t += '\n' + '\n'.join('#print axioms OddPerfect.LowerBoundTwo.%s' % a for a in axioms) + '\n'
    return t


def cost_entry(q):
    a, fs = emit.TAB[q]
    return q.bit_length() * (1 + len(set(fs)))


def split_even(items, k, w):
    """Split a list into k contiguous groups of roughly equal total weight."""
    tot = sum(w(x) for x in items); out, cur, acc = [], [], 0
    for x in items:
        cur.append(x); acc += w(x)
        if acc >= tot * (len(out) + 1) / k and len(out) < k - 1: out.append(cur); cur = []
    out.append(cur)
    return [g for g in out if g]


if __name__ == '__main__':
    B = int(sys.argv[1]); hints = json.load(open(sys.argv[2])); outdir = sys.argv[3]
    plan = dict(x.split(':') for x in sys.argv[4].split())
    record = set() if len(sys.argv) > 5 and sys.argv[5] == 'record' else None
    nT, nG = int(plan['T']), int(plan['G'])
    roots = [int(x) for x in plan['R'].split(',')]
    gen.L = 10 ** B
    sig, split = check_hints(hints)
    pftwo.HINT.update(split)
    os.makedirs(outdir, exist_ok=True)
    # search every root
    rootinfo = []
    for i, p0 in enumerate(roots):
        excl = roots[:i]
        t = search(p0, excl, sig, record)
        s0 = [('pw', p0, 1)] + [('nd', q) for q in excl]
        ins = []; emit.flatten(t, ins)
        rootinfo.append((p0, excl, s0, t))
        print('root', p0, 'instructions', len(ins), flush=True)
    if record is not None:
        used = {'%d,%d' % k: [sig[k][0], {str(q): e for q, e in sorted(sig[k][1].items())}]
                for k in sorted(record)}
        sp = {str(k): str(split[k]) for k in sorted(pftwo.USED_HINTS)}
        json.dump({'sig': used, 'split': sp}, open(os.path.join(outdir, 'hints.json'), 'w'),
                  indent=0, sort_keys=True)
        print('hints', len(used), len(sp))
    # prime table
    keys = sorted(emit.TAB)
    chunks, inner, cnt = [], [], [0]
    def node(ks):
        if not ks: return 'PT.leaf'
        m = len(ks) // 2; q = ks[m]; a, fs = emit.TAB[q]
        return '(PT.node %s %d %d %s\n    %s)' % (node(ks[:m]), q, a, emit.fstr(fs), node(ks[m + 1:]))
    def bst(ks, top=False):
        nm = 'ptable' if top else 'ptab%d' % cnt[0]
        if not top: cnt[0] += 1
        if len(ks) <= TCH:
            chunks.append((nm, node(ks), ks)); return nm
        m = len(ks) // 2; q = ks[m]; a, fs = emit.TAB[q]
        l = bst(ks[:m]); r = bst(ks[m + 1:])
        inner.append((nm, q, a, emit.fstr(fs), l, r)); return nm
    bst(keys, True)
    data = []
    for nm, txt, ks in chunks:
        data.append('/-- Part of the prime table. -/\ndef %s : PT :=\n  %s\n' % (nm, txt))
    for nm, q, a, fs, l, r in inner:
        data.append('/-- %s of the prime table. -/\ndef %s : PT :=\n  PT.node %s %d %d %s %s\n'
                    % ('The root' if nm == 'ptable' else 'A node', nm, l, q, a, fs, r))
    mods = {}
    mods['LowerBoundTwoTable'] = module(['OddPerfect.LowerBound'], 'The prime table',
                                        '\n'.join(data), [])
    groups = split_even(chunks, nT, lambda c: sum(cost_entry(q) for q in c[2]))
    tabmods = []
    for gi, g in enumerate(groups):
        nm = 'LowerBoundTwoTableOk%d' % (gi + 1); tabmods.append(nm)
        body = ''.join('/-- The entries of `%s` pass the Lucas test against the whole table. -/\n'
                       'theorem ok_%s : PT.allOK ptable %s = true := by\n  decide +kernel\n\n'
                       % (c[0], c[0], c[0]) for c in g)
        mods[nm] = module(['OddPerfect.LowerBoundTwoTable'], 'Checks of the prime table, part %d' % (gi + 1),
                          body, ['ok_' + c[0] for c in g])
    body = ('/-- A node of the table is valid when its entry and both subtrees are. -/\n'
            'theorem allOK_node {T l r : PT} {p a : ℕ} {fs : List (ℕ × ℕ)} (h : entryOK T p a fs = true)\n'
            '    (hl : PT.allOK T l = true) (hr : PT.allOK T r = true) :\n'
            '    PT.allOK T (PT.node l p a fs r) = true := by\n'
            '  simp [PT.allOK, h, hl, hr]\n\n')
    for nm, q, a, fs, l, r in inner:
        body += ('/-- The node `%s` of the table is valid. -/\ntheorem ok_%s : PT.allOK ptable %s = true :=\n'
                 '  allOK_node (l := %s) (r := %s) (p := %d) (a := %d) (fs := %s)\n'
                 '    (by decide +kernel) ok_%s ok_%s\n\n' % (nm, nm, nm, l, r, q, a, fs, l, r))
    body += ('/-- Every key of the prime table is prime. -/\n'
             'theorem ptable_prime : ∀ x, ptable.mem x = true → x.Prime :=\n  PT.prime_of_mem ok_ptable\n')
    mods['LowerBoundTwoTablePrime'] = module(['OddPerfect.' + m for m in tabmods], 'The prime table is valid',
                                             body, ['allOK_node'] + ['ok_' + x[0] for x in inner] + ['ptable_prime'])
    # trees: a subtree of at most PART instructions is checked by one run_sound; a larger one is
    # split at its first case split (after single child steps), recursively, and its children
    # are joined by step_sound in the final module
    parts = []       # (name, kid states, instructions)
    def flat(t):
        out = []; emit.flatten(t, out); return out
    def kidstates(t, s):
        p, d, R = t[1], t[2], t[3]
        ks = ([[('ex', p, d - 1)] + s] if d >= 2 else [])
        ks += [[('dv', p, d * r)] + s for r in gen.primes_below(R)] + [[('pw', p, d * R - 1)] + s]
        assert len(ks) == len(t[4])
        return ks
    def splittable(t):
        while t[0] in ('up', 'force'): t = t[3] if t[0] == 'up' else t[4]
        return t[0] == 'rs'
    def prove(s, t):
        if t[0] == 'up':
            nxt = [('pw', t[1], t[2] + 1)] + s
            return ('step_sound ptable_prime (i := .up %d %d) (s := %s)\n      (cs := [%s])\n'
                    '      (by decide +kernel)\n      (List.forall_mem_singleton.2 (%s))'
                    % (t[1], t[2], lst(fact(f) for f in s), lst(fact(f) for f in nxt), prove(nxt, t[3])))
        if t[0] == 'force':
            nxt = [('pw', t[1], t[2])] + s
            return ('step_sound ptable_prime (i := .force %d %d %s) (s := %s)\n      (cs := [%s])\n'
                    '      (by decide +kernel)\n      (List.forall_mem_singleton.2 (%s))'
                    % (t[1], t[2], emit.cs_str(t[3]), lst(fact(f) for f in s), lst(fact(f) for f in nxt),
                       prove(nxt, t[4])))
        assert t[0] == 'rs'
        items, grp = [], []      # items: (list expression, proof)
        def flush():
            if not grp: return
            nm = 'part%d' % len(parts)
            parts.append((nm, [g[0] for g in grp], sum((g[1] for g in grp), [])))
            items.append(('kids%d' % (len(parts) - 1), nm)); del grp[:]
        for ks, sub in zip(kidstates(t, s), t[4]):
            ins = flat(sub)
            if len(ins) > PART and splittable(sub):
                flush(); items.append((lst([lst(fact(f) for f in ks)]),
                                       'List.forall_mem_singleton.2 (%s)' % prove(ks, sub)))
                continue
            if grp and sum(len(g[1]) for g in grp) + len(ins) > PART: flush()
            grp.append((ks, ins))
        flush()
        cs, pr = items[-1]
        for c, q in reversed(items[:-1]):
            cs = '%s ++ (%s)' % (c, cs); pr = 'List.forall_mem_append.2 ⟨%s, %s⟩' % (q, pr)
        return ('step_sound ptable_prime (i := .rs %d %d %d) (s := %s)\n      (cs := %s)\n'
                '      (by decide +kernel)\n      (%s)' % (t[1], t[2], t[3], lst(fact(f) for f in s), cs, pr))
    proofs = [prove(s0, t) for p0, excl, s0, t in rootinfo]
    ggroups = split_even(list(range(len(parts))), nG, lambda i: len(parts[i][2]))
    treemods = []
    for gi, g in enumerate(ggroups):
        nm = 'LowerBoundTwoTree%d' % (gi + 1); treemods.append(nm)
        body, axs = '', []
        for i in g:
            pn, ks, ins = parts[i]
            txt, expr = defs_list('ins%d' % i, ins, 'Instructions of `%s`' % pn)
            body += txt + '\n'
            body += ('/-- States checked by `%s`. -/\ndef kids%d : List (List Fact) :=\n  %s\n\n'
                     % (pn, i, lst(lst(fact(f) for f in k) for k in ks)))
            body += ('/-- A group of subtrees (%d instructions). -/\n'
                     'theorem %s : ∀ s ∈ kids%d, Good (10 ^ %d) s :=\n'
                     '  run_sound ptable_prime (%s) kids%d (by decide +kernel)\n\n'
                     % (len(ins), pn, i, B, expr, i))
            axs.append(pn)
        mods[nm] = module(['OddPerfect.LowerBoundTwoTablePrime'], 'Proof trees, part %d' % (gi + 1),
                          body, axs)
    # final module
    body = 'deriving instance DecidableEq for OddPerfect.LowerBound.Fact\n\n'
    axs = []
    for (p0, excl, s0, t), pr in zip(rootinfo, proofs):
        cond = ', '.join(['`%d ∤ N`' % q for q in excl] + ['`%d ∣ N`' % p0])
        body += ('/-- The tree for %s. -/\ntheorem good%d : Good (10 ^ %d) %s :=\n  %s\n\n'
                 % (cond, p0, B, lst(fact(f) for f in s0), pr))
        axs.append('good%d' % p0)
    P = max(roots) + 1
    while not all(P % d for d in range(2, P)): P += 1
    tmp = os.path.join(outdir, 'tail.tmp')
    mktail.main(B, P, tmp)
    tail = open(tmp).read(); os.remove(tmp)
    tail = tail.replace('\nend OddPerfect.LowerBound\n', '')
    tail = tail.replace('/-! ## The lower bound -/\n', '')
    body += tail
    axs += ['card_primeFactors_of_no_prime_lt_%d' % P, 'lower_bound']
    mods['LowerBoundTwo'] = module(['OddPerfect.' + m for m in treemods], 'A lower bound `10 ^ %d`' % B,
                                   body, axs)
    for nm, txt in mods.items():
        open(os.path.join(outdir, nm + '.lean'), 'w').write(txt)
    print('table', len(keys), 'chunks', len(chunks), 'modules', len(mods))
    for nm in mods: print(nm, len(mods[nm]))
    print('parts', len(parts), 'largest', max(len(x[2]) for x in parts))
