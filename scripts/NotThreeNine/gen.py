# Untrusted helper script for the OddPerfect Lean library.
# Generates OddPerfect/NotThreeNine.lean: the search state with no listed primes, eight further
# primes, all above 4 (an odd perfect number with exactly eight prime factors and 3 not dividing
# it), is closed by windows of the next prime (OmegaSevenSearch.closed_of_window) until every
# child has at most CAP mirror nodes; each such child is closed by one `run 60` kernel check of
# the verified engine OmegaSevenEngine.run.
# Run: python3 -I gen.py OUTDIR (OUTDIR must exist). engine.py and plan.py of scripts/OmegaSeven
# are found next to this script or in ../OmegaSeven.
# Requires: Python 3 standard library. Deterministic. Running time: a few seconds.
# Untrusted: every result is checked again by the Lean kernel.
# License: GPL 3, same as the repository.
import sys, os
here = os.path.dirname(os.path.abspath(__file__))
sys.path[:0] = [here, os.path.join(here, '..', 'OmegaSeven')]
sys.argv, out = sys.argv[:1], sys.argv[1]
import engine as E
import plan as P

CAP = 3000

def lit(l): return '[' + ', '.join('⟨%d, %d, false⟩' % (p, k) for p, k, _ in l) + ']'
def name(l): return 'c_' + '_'.join(str(e[0]) for e in l) if l else 'c_root'

thms, total, biggest = [], [0], [0]

def node(l, j, m):
    r, s = E.run(l, j, m, P.lad, P.Y, P.Q, 60)
    assert r is True, (l, j, m)
    n = s['nodes']
    stmt = 'Closed %s %d %d' % (lit(l), j, m)
    if n <= CAP:
        total[0] += n; biggest[0] = max(biggest[0], n)
        thms.append((name(l), stmt, '  closed_of_run (f := 60) (by decide +kernel)', n))
        return
    w = P.window(l, j, m)
    kids = []
    for q in w:
        c = l + [(q, E.kmin(q), False)]
        node(c, j - 1, q); kids.append(name(c))
    body = ['  apply closed_of_window (by decide) (by decide +kernel)',
            '  rw [show window %s %d %d = [%s] by decide +kernel]' % (lit(l), j, m, ', '.join(map(str, w))),
            '  simp only [List.forall_mem_cons, List.not_mem_nil, IsEmpty.forall_iff, implies_true, and_true]',
            '  exact ⟨%s⟩' % ', '.join(kids)]
    thms.append((name(l), stmt + ' := by', '\n'.join(body), None))

node([], 8, 4)

H = '''import OddPerfect.OmegaSevenEngine
import OddPerfect.SmallPrimes

/-!
# Odd perfect numbers not divisible by 3 have at least nine distinct prime factors

`nine_le_card_primeFactors_of_not_three_dvd`: if `3 ∤ N` for an odd perfect number `N`, then `N`
has at least nine distinct prime factors. This is known mathematics: Hagis (1983) and Kishore
(1983) proved eleven, and Nielsen (2007) proved twelve, for odd perfect numbers not divisible by
`3`. Only nine is proved here.

Proof. By `eight_le_card_primeFactors_of_not_three_dvd` it suffices to exclude exactly eight
prime factors. Such an `N` satisfies the search state with no listed primes and eight further
primes, all above `4`. That state is closed by windows of the next prime
(`OmegaSevenSearch.closed_of_window`), applied until every child has at most %d search nodes
in the Python mirror `scripts/OmegaSeven/engine.py`; each such child is closed by one kernel
check of the verified engine `OmegaSevenEngine.run`. No structural fact beyond the engine's own
cuts (abundancy bounds, at most one odd exponent, prime cofactors of the divisor sums) is
used. Mirror nodes in this file: %d in %d checks, the largest %d. Generated by
`scripts/NotThreeNine/gen.py`.
-/

namespace OddPerfect.NotThreeNine

open OmegaSixSearch (Ent Holds kmin)
open OmegaSevenSearch (Closed closed_of_window window)
open OmegaSevenEngine (closed_of_run)

set_option maxRecDepth 100000
'''
nleaf = sum(1 for t in thms if t[3] is not None)
parts = [H % (CAP, total[0], nleaf, biggest[0])]
for nm, stmt, proof, n in thms:
    if nm == 'c_root':
        parts.append('/-- Exactly eight prime factors, none of them `3`, is impossible. -/\ntheorem closed_root :\n    %s\n%s\n' % (stmt, proof))
    elif n is None:
        parts.append('private theorem %s :\n    %s\n%s\n' % (nm, stmt, proof))
    else:
        parts.append('private theorem %s :\n    %s :=\n%s\n' % (nm, stmt, proof))
parts.append('''end OddPerfect.NotThreeNine

namespace OddPerfect

open OmegaSixSearch (Holds)

/-- If `3 ∤ N` for an odd perfect number `N`, then `N` has at least nine distinct prime factors.
Known: Hagis (1983) and Kishore (1983) proved eleven, Nielsen (2007) twelve. -/
theorem nine_le_card_primeFactors_of_not_three_dvd {N : ℕ} (h : OddPerfect N) (h3 : ¬ 3 ∣ N) :
    9 ≤ N.primeFactors.card := by
  have h8 := eight_le_card_primeFactors_of_not_three_dvd h h3
  by_contra hlt
  have hk : N.primeFactors.card = 8 := by omega
  have H : Holds N [] 8 4 := by
    refine ⟨h, by simp, by simp, by simp [hk], ?_⟩
    intro q hq _
    have hqp := Nat.prime_of_mem_primeFactors hq
    have hd := Nat.dvd_of_mem_primeFactors hq
    have : q ≠ 2 := fun e => h.not_two_dvd (e ▸ hd)
    have : q ≠ 3 := fun e => h3 (e ▸ hd)
    have : q ≠ 4 := fun e => by subst e; norm_num at hqp
    have := hqp.two_le
    omega
  exact NotThreeNine.closed_root N H

end OddPerfect

#print axioms OddPerfect.NotThreeNine.closed_root
#print axioms OddPerfect.nine_le_card_primeFactors_of_not_three_dvd
''')
open(os.path.join(out, 'NotThreeNine.lean'), 'w').write('\n'.join(parts))
print('checks', nleaf, 'nodes', total[0], 'largest', biggest[0])
