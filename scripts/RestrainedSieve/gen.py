"""Generate the witness data of the reciprocal sum sieve for the restrained family.

Usage: python3 -I gen.py X LIMBS_PER_BLOCK BLOCKS_PER_MODULE OUTDIR [--only-stats]

For every odd n with B <= n <= X (B = 132257) the generator writes one witness w < 2^18:
  * w = smallest prime factor of n, when n is composite (then 2 <= w < n, w | n);
  * w = smallest prime t >= 5 with t < B and t | n^2 + n + 1, when n is prime and such a t
    exists (then t is odd and not divisible by 3);
  * w = 0 otherwise: n belongs to the list T.
Sixteen witnesses form one limb (base 2^18, first witness lowest). The checker
`RestrainedElevenCheck.runL` replays the same integer operations: for n in T the fixed point
accumulator becomes ceil(acc * n * X / ((n - 1) * (X + 1))). Standard library only;
deterministic output.
"""
import hashlib
import math
import os
import sys
from fractions import Fraction

B = 132257
DIG = 18
PER = 16
SCALE = 64


def spf_sieve(n):
    spf = list(range(n + 1))
    for i in range(2, math.isqrt(n) + 1):
        if spf[i] == i:
            for j in range(i * i, n + 1, i):
                if spf[j] == j:
                    spf[j] = i
    return spf


def witnesses(X):
    spf = spf_sieve(X)
    lo = B
    cnt = (X + 1 - lo) // 2
    wit = [0] * cnt
    pending = {}
    for i in range(cnt):
        n = lo + 2 * i
        if spf[n] != n:
            wit[i] = spf[n]
        else:
            pending[n] = i
    # primes t = 1 mod 3 below B, ascending: roots of x^2 + x + 1 mod t are the cube roots of 1
    for t in range(7, B, 6):
        if spf[t] != t:
            continue
        g = 2
        while True:
            z = pow(g, (t - 1) // 3, t)
            if z != 1:
                break
            g += 1
        for r in (z, z * z % t):
            assert (r * r + r + 1) % t == 0
            first = lo + ((r - lo) % t)
            for n in range(first, X + 1, t):
                if n % 2 == 1 and n in pending:
                    i = pending[n]
                    if wit[i] == 0:
                        wit[i] = t
    for i in range(cnt):
        n = lo + 2 * i
        w = wit[i]
        assert 0 <= w < 2 ** DIG
        if w:
            comp = 2 <= w < n and n % w == 0
            sq = 2 <= w < B and w % 2 == 1 and w % 3 != 0 and (n * n + n + 1) % w == 0
            assert comp or sq
    return wit


def ceil_div(a, b):
    return (a + b - 1) // b


def step(X, n, acc):
    return ceil_div(acc * n * X, (n - 1) * (X + 1))


def lean_header(title, body):
    return "/-!\n# " + title + "\n\n" + body + "\n-/\n"


def main():
    X = int(sys.argv[1])
    LB = int(sys.argv[2])
    BM = int(sys.argv[3])
    out = sys.argv[4]
    only = "--only-stats" in sys.argv
    cmd = "scripts/RestrainedSieve/gen.py %d %d %d" % (X, LB, BM)
    wit = witnesses(X)
    cnt = len(wit)
    assert cnt % PER == 0, cnt
    T = [B + 2 * i for i in range(cnt) if wit[i] == 0]
    ST = sum(Fraction(1, n - 1) for n in T)
    print("odd numbers", cnt, "|T|", len(T), "S_T", float(ST))
    # fixed point chain, block boundaries every LB limbs
    acc = 1 << SCALE
    exact = Fraction(1)
    limbs = []
    for k in range(cnt // PER):
        W = 0
        for j in range(PER):
            W |= wit[k * PER + j] << (DIG * j)
        limbs.append(W)
    blocks = []
    nlimb = len(limbs)
    for s in range(0, nlimb, LB):
        part = limbs[s:s + LB]
        lo = B + 2 * PER * s
        a0 = acc
        for idx in range(s * PER, (s + len(part)) * PER):
            if wit[idx] == 0:
                n = B + 2 * idx
                acc = step(X, n, acc)
                exact *= Fraction(n * X, (n - 1) * (X + 1))
        hi = lo + 2 * PER * len(part)
        blocks.append((lo, hi, a0, acc, part))
    assert blocks[-1][1] == X + 1
    aF = acc
    assert Fraction(aF, 1 << SCALE) >= exact
    # largest K with 3 B aF (X+1)^K <= 4 (B-1) 2^64 X^K
    lg = (math.log(4 / 3) - math.log(B / (B - 1)) - math.log(aF / 2 ** SCALE)) / math.log(
        (X + 1) / X)
    K = int(lg) + 3

    def ok(k):
        return 3 * B * aF * (X + 1) ** k <= 4 * (B - 1) * (1 << SCALE) * X ** k

    while not ok(K):
        K -= 1
    assert ok(K) and not ok(K + 1)
    print("aF", aF, "K", K, "omega >=", K + 3, "E >=", (K + 1) // 2 + ((K + 1) // 2) % 2)
    print("blocks", len(blocks))
    if only:
        return
    mods = [blocks[i:i + BM] for i in range(0, len(blocks), BM)]
    hashes = []
    for mi, mb in enumerate(mods, 1):
        name = "RestrainedElevenData%d" % mi
        L = []
        L.append("import OddPerfect.RestrainedElevenCheck\n")
        L.append(lean_header(
            "Restrained odd perfect numbers: sieve witnesses, part %d of %d" % (mi, len(mods)),
            "Generated by `python3 -I " + cmd + " <outdir>`\n"
            "(deterministic). Each block holds the witnesses of the odd numbers of its\n"
            "range, sixteen per limb in base `2 ^ 18`; `runL` checks every witness and\n"
            "carries the fixed point bound of the product over the numbers without a\n"
            "witness. This part covers the odd numbers `%d ≤ n < %d`." %
            (mb[0][0], mb[-1][1])))
        L.append("namespace OddPerfect\n\nnamespace RestrainedElevenCheck\n")
        names = []
        for (lo, hi, a0, a1, part) in mb:
            bn = "b%d" % lo
            L.append("/-- Witness limbs of the odd numbers `%d ≤ n < %d`. -/" % (lo, hi))
            L.append("def w%s : List ℕ := [" % bn)
            for i, W in enumerate(part):
                L.append("  %d%s" % (W, "," if i + 1 < len(part) else "]"))
            L.append("")
            L.append("/-- The block `%d ≤ n < %d` is accepted. -/" % (lo, hi))
            L.append("theorem ok_%s : runL %d w%s %d" % (bn, X, bn, lo))
            L.append("    %d %d %d = true := by" % (a0, hi, a1))
            L.append("  decide +kernel\n")
            names.append("ok_" + bn)
        lo0, a00 = mb[0][0], mb[0][2]
        hiL, aL = mb[-1][1], mb[-1][3]
        if mi == 1:
            lo, a0, W = mb[0][0], mb[0][2], mb[0][4][0]
            j = next(j for j in range(PER) if wit[j] not in (0,))
            n = lo + 2 * j
            bad = W + ((wit[j] + 2) - wit[j]) * (1 << (DIG * j))
            wb = wit[j] + 2
            assert n % wb != 0 and (n * n + n + 1) % wb != 0
            big = 1 << 200
            L.append("/-- Positive twin of the control: the first limb as generated. -/")
            L.append("theorem first_limb_ok : runL %d" % X)
            L.append("    [%d]" % W)
            L.append("    %d %d %d" % (lo, a0, lo + 32))
            L.append("    %d = true := by" % big)
            L.append("  decide +kernel\n")
            L.append("/-- Negative control: the witness `%d` of `%d` replaced by `%d`, which" %
                     (wit[j], n, wb))
            L.append("divides neither `%d` nor `%d ^ 2 + %d + 1`, is rejected. -/" % (n, n, n))
            L.append("theorem first_limb_bad : runL %d" % X)
            L.append("    [%d]" % bad)
            L.append("    %d %d %d" % (lo, a0, lo + 32))
            L.append("    %d = false := by" % big)
            L.append("  decide +kernel\n")
            names += ["first_limb_ok", "first_limb_bad"]
        cn = "cert%d" % mi
        L.append("/-- The certificate of the odd numbers `%d ≤ n < %d`. -/" % (lo0, hiL))
        L.append("theorem %s : Cert %d %d %d" % (cn, X, lo0, hiL))
        L.append("    %d %d := by" % (a00, aL))
        for j, (lo, hi, a0, a1, part) in enumerate(mb):
            L.append("  have c%d : Cert %d %d %d" % (j, X, lo, hi))
            L.append("      %d %d := runL_sound ok_b%d" % (a0, a1, lo))
            if j > 0:
                L.append("  have c%d := cert_trans c%d c%d" % (j, j - 1, j))
        L.append("  exact c%d\n" % (len(mb) - 1))
        names.append(cn)
        L.append("end RestrainedElevenCheck\n\nend OddPerfect\n")
        for nm in names:
            L.append("#print axioms OddPerfect.RestrainedElevenCheck." + nm)
        txt = "\n".join(L) + "\n"
        for line in txt.split("\n"):
            assert len(line) <= 100, line[:60]
        path = os.path.join(out, name + ".lean")
        with open(path, "w") as f:
            f.write(txt)
        hashes.append((name, hashlib.sha256(txt.encode()).hexdigest()))
    for nm, hx in hashes:
        print(nm, hx)


if __name__ == "__main__":
    main()
