"""Text of the Lean module MixedIndexThreePrimes (used by gen3.py).
Primes below SMALL: trial division up to the square root (`RestrainedSeven.oddPrime`).
Larger primes: Pratt entries in blocks, each block checked with the small primes and the
earlier blocks as known primes."""

SMALL = 10 ** 6

HEAD = """import OddPerfect.MixedIndexThreeCheck
import OddPerfect.RestrainedSevenCheck

/-!
# The mixed index family 3, 5, 7 with special prime 5: certified primes

Generated by the script `gen3.py`. The list `primes` holds every forced prime of the
`MixedIndexThree` trees. A prime below `1000000` is certified by trial division up to its square
root (`RestrainedSeven.oddPrime`); the lists `sm<i>` hold those that are needed. A larger prime is
certified by the Pratt blocks `pb<i>`, checked block by block, each block using the primes of the
lists `sm<i>` and of the earlier blocks.
-/

namespace OddPerfect

namespace MixedIndexThree
"""

SBLOCK = """
/-- Primes below `1000000`, part {i}. -/
def sm{i} : List ℕ :=
  [{body}]

"""

SALL = """
/-- All primes below `1000000` that are needed. -/
def smAll : List ℕ :=
  {names}

/-- Every member of `smAll` passes trial division. -/
theorem smAll_ok : smAll.all RestrainedSeven.oddPrime = true := by decide +kernel

/-- Every member of `smAll` is prime. -/
theorem smAll_prime : ∀ q ∈ smAll, q.Prime := fun q hq =>
  RestrainedSeven.oddPrime_sound (List.all_eq_true.mp smAll_ok q hq)
"""

PBLOCK = """
/-- Pratt block {i}: entries `(p, a, prime factors of p - 1)`. -/
def pb{i} : List (ℕ × ℕ × List ℕ) :=
  [{body}]

/-- Pratt block {i} is accepted, given the small primes and the earlier blocks. -/
theorem pb{i}_ok : Pratt.checkAux (smAll ++ ({prev}).map Prod.fst) pb{i} = true := by
  decide +kernel
"""

PLIST = """
/-- Forced primes, part {i}. -/
def pl{i} : List ℕ :=
  [{body}]
"""

TAIL = """
/-- The primes certified by the Pratt blocks. -/
def pnames : List ℕ :=
  ({allb}).map Prod.fst

/-- Every number certified by a Pratt block is prime. -/
theorem pnames_prime : ∀ q ∈ pnames, q.Prime := by
{pf}

/-- The forced primes of the trees. -/
def primes : List ℕ :=
  {pls}

/-- A prime by trial division below `1000000`, or certified by a Pratt block. -/
def primeB (t : ℕ) : Bool :=
  (decide (t < 1000000) && RestrainedSeven.oddPrime t) || pnames.contains t

/-- Every forced prime passes `primeB`. -/
theorem primes_ok : primes.all primeB = true := by decide +kernel

/-- Every forced prime is prime. -/
theorem primes_prime : ∀ t ∈ primes, t.Prime := by
  intro t ht
  have h := List.all_eq_true.mp primes_ok t ht
  simp only [primeB, Bool.or_eq_true, Bool.and_eq_true, decide_eq_true_eq,
    List.contains_iff_mem] at h
  rcases h with ⟨_, h⟩ | h
  · exact RestrainedSeven.oddPrime_sound h
  · exact pnames_prime t h

end MixedIndexThree

end OddPerfect

{prints}#print axioms OddPerfect.MixedIndexThree.smAll_prime
#print axioms OddPerfect.MixedIndexThree.pnames_prime
#print axioms OddPerfect.MixedIndexThree.primes_ok
#print axioms OddPerfect.MixedIndexThree.primes_prime
"""

NIL = '([] : List (ℕ × ℕ × List ℕ))'


def chunks_of(xs, blk):
    return [xs[i:i + blk] for i in range(0, len(xs), blk)]


def primes_module(P, pc, blk=150):
    big = [e for e in pc if e[0] >= SMALL]
    need = set(p for p in P if 2 < p < SMALL)
    for p, a, fs in big:
        need |= set(q for q in fs if 2 < q < SMALL)
    small = sorted(need)
    out = [HEAD]
    sb = chunks_of(small, blk)
    for i, b in enumerate(sb, 1):
        out.append(SBLOCK.format(i=i, body=', '.join(map(str, b))))
    out.append(SALL.format(names=' ++ '.join('sm%d' % i for i in range(1, len(sb) + 1))))
    bl = chunks_of(big, blk)
    for i, b in enumerate(bl, 1):
        prev = ' ++ '.join('pb%d' % j for j in range(1, i)) or NIL
        out.append(PBLOCK.format(i=i, prev=prev, body=',\n   '.join(
            '(%d, %d, [%s])' % (p, a, ', '.join(map(str, fs))) for p, a, fs in b)))
    pf = ['  have h0 : ∀ q ∈ smAll ++ (%s).map Prod.fst, q.Prime := by' % NIL,
          '    simpa using smAll_prime']
    for i in range(1, len(bl) + 1):
        prev = ' ++ '.join('pb%d' % j for j in range(1, i)) or NIL
        pf += ['  have h%d : ∀ q ∈ smAll ++ ((%s) ++ pb%d).map Prod.fst, q.Prime := by' % (i, prev, i),
               '    intro q hq',
               '    rw [List.map_append, ← List.append_assoc, List.mem_append] at hq',
               '    rcases hq with hq | hq',
               '    · exact h%d q hq' % (i - 1),
               '    · obtain ⟨e, he, rfl⟩ := List.mem_map.mp hq',
               '      exact Pratt.checkAux_sound _ pb%d h%d pb%d_ok e he' % (i, i - 1, i)]
    allb = ' ++ '.join('pb%d' % j for j in range(1, len(bl) + 1))
    lastprev = ' ++ '.join('pb%d' % j for j in range(1, len(bl))) or NIL
    pf += ['  intro q hq',
           '  have hq\' : q ∈ ((%s) ++ pb%d).map Prod.fst := hq' % (lastprev, len(bl)),
           '  exact h%d q (List.mem_append_right _ hq\')' % len(bl)]
    pls = [P]  # one literal list: membership tests in the trees are cheaper than on an append
    for i, b in enumerate(pls, 1):
        out.append(PLIST.format(i=i, body=', '.join(map(str, b))))
    prints = '#print axioms OddPerfect.MixedIndexThree.smAll_ok\n'
    prints += ''.join('#print axioms OddPerfect.MixedIndexThree.pb%d_ok\n' % i for i in range(1, len(bl) + 1))
    out.append(TAIL.format(allb=allb, pf='\n'.join(pf),
                           pls=' ++ '.join('pl%d' % i for i in range(1, len(pls) + 1)), prints=prints))
    return ''.join(out), len(small), len(big)
