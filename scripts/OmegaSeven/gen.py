# Untrusted helper script for the OddPerfect Lean library.
# Generates OmegaSevenRoots{A,B,...}.lean from plan.json (written by plan.py). The child of [3, 5]
# with next prime 13 is left out (it is closed in OmegaSevenPilot.lean). Theorems are emitted in
# dependency order and packed into files of at most BUDGET mirror nodes; a theorem used in a
# later file is public.
# Used by: OddPerfect/OmegaSevenRootsA.lean .. OmegaSevenRootsD.lean (every theorem).
# Run: python3 gen.py OUTDIR 60000 (in the folder that holds plan.json; OUTDIR must exist).
# BUDGET 60000 reproduces the four library files; the default, 70000, packs them differently.
# Requires: Python 3 standard library. Deterministic. Running time: under a second.
# Untrusted: every result is checked again by the Lean kernel.
# Paths: plan.json is read from the current folder; the Lean files are written to OUTDIR.
# License: GPL 3, same as the repository.
import sys, json
P = json.load(open('plan.json'))
def kmin(q): return 1 if q % 4 == 1 else 2
def lit(l): return '[' + ', '.join('⟨%d, %d, %s⟩' % (p, k, 'true' if ex else 'false') for p, k, ex in l) + ']'
def nv(p, k):
    v = lambda e: e % 2 == 0 or (p % 4 == 1 and e % 4 == 1)
    return k + 1 if v(k + 1) else k + 2

class G:
    def __init__(s, tag): s.tag, s.n, s.out = tag, 0, []
    def name(s):
        s.n += 1; return '%s_%d' % (s.tag, s.n)
    def thm(s, name, stmt, proof, public=False, cost=0, refs=()):
        s.out.append(dict(name=name, body='theorem %s :\n    %s :=\n  %s\n' % (name, stmt, proof),
                          public=public, cost=cost, refs=list(refs)))
    def node(s, t, name=None, stmt=None, public=False):
        name = name or s.name()
        l = [tuple(e) for e in t['l']]; j, m = t['j'], t['m']
        stmt = stmt or 'Closed %s %d %d' % (lit(l), j, m)
        if t['t'] == 'leaf':
            s.thm(name, stmt, 'closed_of_run (f := 60) (by decide +kernel)', public, t['n'])
        elif t['t'] == 'split':
            i = t['i']; p, k, ex = l[i]; assert not ex
            a = s.node(t['a']); b = s.node(t['b'])
            assert [tuple(e) for e in t['a']['l']] == l[:i] + [(p, k, True)] + l[i+1:]
            assert [tuple(e) for e in t['b']['l']] == l[:i] + [(p, nv(p, k), False)] + l[i+1:]
            s.thm(name, stmt, 'closed_of_split (pre := %s) (post := %s) (by decide) %s %s'
                  % (lit(l[:i]), lit(l[i+1:]), a, b), public, 0, (a, b))
        else:
            assert j >= 1
            pieces, pos, refs = [], m + 1, []
            for g in t['g']:
                if g['t'] == 'ival':
                    assert g['a'] == pos; pos = g['b']; nm = s.name()
                    s.thm(nm, '∀ q, %d ≤ q → q < %d → Closed (%s ++ [⟨q, kmin q, false⟩]) (%d - 1) q'
                          % (g['a'], g['b'], lit(l), j), 'ival_sound (by decide +kernel)', False, g['n'])
                    pieces.append((g['b'], nm)); refs.append(nm)
                else:
                    q = g['q']; assert q == pos; pos = q + 1
                    c = s.node(g['c']); refs.append(c)
                    pieces.append((q + 1, '(cover_one (a := %d) (b := %d) rfl %s)' % (q, q + 1, c)))
            assert pos == t['B'] + 1, (pos, t['B'])
            chain = pieces[-1][1]
            for b, nm in reversed(pieces[:-1]):
                chain = '(cover_join (b := %d) %s\n    %s)' % (b, nm, chain)
            s.thm(name, stmt, 'closed_of_cover (a := %d) (c := %d) (by decide) (by decide +kernel)\n'
                  '    (by decide +kernel) (by decide +kernel)\n    %s' % (m + 1, t['B'] + 1, chain), public, 0, refs)
        return name

def leaves(t):
    if t['t'] in ('leaf', 'ival'): return [t]
    if t['t'] == 'split': return leaves(t['a']) + leaves(t['b'])
    if t['t'] == 'one': return leaves(t['c'])
    return [x for g in t['g'] for x in leaves(g)]

def rootinfo(t):
    l = [tuple(e) for e in t['l']]
    q = l[-1][0]
    if len(l) == 3: return 'closed_3_5_%d' % q, '[⟨3, 2, false⟩, ⟨5, 1, false⟩]', 4, q
    return 'closed_3_5_17_%d' % q, '[⟨3, 2, false⟩, ⟨5, 1, false⟩, ⟨17, 1, false⟩]', 3, q

trees = [t for t in P['trees'] if not (len(t['l']) == 3 and t['l'][2][0] == 13)]
def nodes(t): return sum(x['n'] for x in leaves(t))
HEAD = '''import OddPerfect.%s

/-!
# Odd perfect numbers with six prime factors: kernel runs, part %s

The theorems `closed_3_5_p` (resp. `closed_3_5_17_q`) close the child state of the prefix
`3, 5` (resp. `3, 5, 17`) whose next prime is `p` (resp. `q`), as produced by
`OmegaSevenSearch.closed_of_window`; they are assembled in `OddPerfect/OmegaSevenFinal.lean`.
The proofs run the verified engine `OmegaSevenEngine.run` in the kernel, cut into checks of at
most 6000 search nodes (Python mirror count) by the exponent splits and covers of
`OddPerfect/OmegaSevenSplit.lean`. Generated by the scripts `plan.py` (cut plan, from the mirror
`engine.py`) and `gen.py`. Mirror nodes in this file: %d.
-/

namespace OddPerfect.OmegaSevenRoots

open OmegaSixSearch (Ent kmin)
open OmegaSevenSearch (Closed)
open OmegaSevenEngine (closed_of_run)
open OmegaSevenSplit

set_option maxRecDepth 100000

'''
out = sys.argv[1]; BUDGET = int(sys.argv[2]) if len(sys.argv) > 2 else 70000
g = G('c')
for t in trees:
    nm, base, j, q = rootinfo(t)
    g.tag = nm.replace('closed_', 'n'); g.n = 0
    g.node(t, nm, 'Closed (%s ++ [⟨%d, kmin %d, false⟩]) (%d - 1) %d' % (base, q, q, j, q), True)
files, cur, acc = [], [], 0
for e in g.out:
    if cur and acc + e['cost'] > BUDGET: files.append(cur); cur, acc = [], 0
    cur.append(e); acc += e['cost']
files.append(cur)
where = {e['name']: i for i, f in enumerate(files) for e in f}
for i, f in enumerate(files):
    for e in f:
        for r in e['refs']:
            if where[r] != i: [x for x in files[where[r]] if x['name'] == r][0]['public'] = True
letters = 'ABCDEFGHIJ'
for i, f in enumerate(files):
    imp = 'OmegaSevenSplit' if i == 0 else 'OmegaSevenRoots' + letters[i - 1]
    txt = HEAD % (imp, letters[i], sum(e['cost'] for e in f))
    txt += '\n'.join(('' if e['public'] else 'private ') + e['body'] for e in f)
    txt += '\nend OddPerfect.OmegaSevenRoots\n\n' + ''.join(
        '#print axioms OddPerfect.OmegaSevenRoots.%s\n' % e['name'] for e in f if e['public'])
    open('%s/OmegaSevenRoots%s.lean' % (out, letters[i]), 'w').write(txt)
    print(letters[i], 'nodes', sum(e['cost'] for e in f), 'theorems', len(f), 'public', sum(e['public'] for e in f),
          'checks', sum(1 for e in f if e['cost']), 'kB', len(txt) // 1000)
