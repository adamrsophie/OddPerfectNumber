# Untrusted helper script for the OddPerfect Lean library.
# Generates OddPerfect/OmegaSevenFiveSeven.lean: the state [3] (exponent at least 2) with six
# further primes, all above 7, is closed through its window [11, 13, 17, 19]; each child is cut
# by the planner plan.py of scripts/OmegaSeven at CAP 6000 and closed by `run 60` kernel checks.
# Run: python3 gen_five_seven.py OUTDIR (OUTDIR must exist); plan.py and engine.py of
# scripts/OmegaSeven must sit next to this script.
# Requires: Python 3 standard library. Deterministic. Running time: a few seconds.
# Untrusted: every result is checked again by the Lean kernel.
# License: GPL 3, same as the repository.
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.argv, out = sys.argv[:1] + ['6000'], sys.argv[1]
import plan as PL
import engine as E

kmin = E.kmin
def lit(l): return '[' + ', '.join('⟨%d, %d, %s⟩' % (p, k, 'true' if ex else 'false') for p, k, ex in l) + ']'

class G:
    def __init__(s, tag): s.tag, s.n, s.out = tag, 0, []
    def name(s):
        s.n += 1; return '%s_%d' % (s.tag, s.n)
    def thm(s, name, stmt, proof, public=False, doc=None):
        d = '/-- %s -/\n' % doc if doc else ''
        s.out.append(d + ('' if public else 'private ') + 'theorem %s :\n    %s :=\n  %s\n' % (name, stmt, proof))
    def node(s, t, name=None, stmt=None, public=False, doc=None):
        name = name or s.name()
        l = [tuple(e) for e in t['l']]; j, m = t['j'], t['m']
        stmt = stmt or 'Closed %s %d %d' % (lit(l), j, m)
        if t['t'] == 'leaf':
            s.thm(name, stmt, 'closed_of_run (f := 60) (by decide +kernel)', public, doc)
        elif t['t'] == 'split':
            i = t['i']; p, k, ex = l[i]; assert not ex
            a = s.node(t['a']); b = s.node(t['b'])
            assert [tuple(e) for e in t['a']['l']] == l[:i] + [(p, k, True)] + l[i+1:]
            assert [tuple(e) for e in t['b']['l']] == l[:i] + [(p, E.nextValid(p, k), False)] + l[i+1:]
            s.thm(name, stmt, 'closed_of_split (pre := %s) (post := %s) (by decide) %s %s'
                  % (lit(l[:i]), lit(l[i+1:]), a, b), public, doc)
        else:
            raise Exception(('cover node not expected', l, j, m))
        return name

root = [(3, 2, False)]
w = PL.window(root, 6, 7)
assert w == [11, 13, 17, 19], w
g = G('n')
total = 0
for q in w:
    t = PL.plan(root + [(q, kmin(q), False)], 5, q)
    L = PL.leaves(t); total += sum(x['n'] for x in L)
    print(q, 'leaves', len(L), 'max', max(x['n'] for x in L), 'sum', sum(x['n'] for x in L))
    g.tag = 'n3_%d' % q; g.n = 0
    g.node(t, 'closed_3_%d' % q, 'Closed ([⟨3, 2, false⟩] ++ [⟨%d, kmin %d, false⟩]) (6 - 1) %d' % (q, q, q),
           True, 'Seven prime factors with `3, %d` the two smallest is impossible.' % q)

HEAD = '''import OddPerfect.OmegaSevenSplit
import OddPerfect.SmallPrimes

/-!
# Odd perfect numbers with seven prime factors are divisible by 5 or by 7

`five_or_seven_dvd_of_card_primeFactors_eq_seven`: an odd perfect number with exactly seven
distinct prime factors is divisible by `5` or by `7`. This is a known consequence of the theorem
of Chein (1979) and Hagis (1980) that an odd perfect number has at least eight distinct prime
factors, which is not proved here.

Proof. By `eight_le_card_primeFactors_of_not_three_dvd`, `3 ∣ N`. If `5 ∤ N` and `7 ∤ N`, then
`N` satisfies the search state `[3]` (exponent at least two) with six further prime factors, all
above `7`. Its window (`OmegaSevenSearch.closed_of_window`) is `11, 13, 17, 19`; each child is
closed by the verified engine `OmegaSevenEngine.run`, cut into checks of at most 6000 search
nodes (Python mirror count) by the exponent splits of `OddPerfect/OmegaSevenSplit.lean`. The
case analysis was found outside Lean, by the mirror `engine.py` and the planner `plan.py` of
`OddPerfect/OmegaSevenRoots*.lean`, and is rechecked here by the kernel. Mirror nodes in this
file: %d. Generated by `gen_five_seven.py`.

The states where `5` or `7` divides `N` (in particular the second smallest prime factor `7`) are
not treated here.
-/

namespace OddPerfect.OmegaSevenFiveSeven

open OmegaSixSearch (Ent Holds kmin kmin_le)
open OmegaSevenSearch (Closed closed_of_window window)
open OmegaSevenEngine (closed_of_run)
open OmegaSevenSplit

set_option maxRecDepth 100000

'''

TAIL = '''/-- Seven prime factors with `3` the smallest and all others above `7` is impossible. -/
theorem closed_no_five_seven : Closed [⟨3, 2, false⟩] 6 7 := by
  apply closed_of_window (by decide) (by decide +kernel)
  rw [show window [⟨3, 2, false⟩] 6 7 = [11, 13, 17, 19] by decide +kernel]
  simp only [List.forall_mem_cons, List.not_mem_nil, IsEmpty.forall_iff, implies_true, and_true]
  exact ⟨closed_3_11, closed_3_13, closed_3_17, closed_3_19⟩

end OddPerfect.OmegaSevenFiveSeven

namespace OddPerfect

open OmegaSixSearch (Ent Holds kmin_le)

private theorem holds_root3_seven {N : ℕ} (h : OddPerfect N) (h7 : N.primeFactors.card = 7)
    (h3 : 3 ∈ N.primeFactors) (hm : ∀ q ∈ N.primeFactors, q ≠ 3 → 7 < q) :
    Holds N [⟨3, 2, false⟩] 6 7 := by
  refine ⟨h, by simp, ?_, by simp [h7], ?_⟩
  · intro e he
    simp only [List.mem_singleton] at he
    subst he
    exact ⟨h3, kmin_le h h3, fun h => by simp at h⟩
  · intro q hq hn
    simp only [List.map_cons, List.map_nil, List.mem_singleton] at hn
    exact hm q hq hn

/-- An odd perfect number with exactly seven distinct prime factors is divisible by `5` or by
`7`. A known consequence of the eight prime factor theorem of Chein and Hagis. -/
theorem five_or_seven_dvd_of_card_primeFactors_eq_seven {N : ℕ} (h : OddPerfect N)
    (h7 : N.primeFactors.card = 7) : 5 ∣ N ∨ 7 ∣ N := by
  by_contra hc
  rw [not_or] at hc
  obtain ⟨h5, h7d⟩ := hc
  have h3 : 3 ∈ N.primeFactors := by
    by_contra h3
    have := eight_le_card_primeFactors_of_not_three_dvd h
      (fun hd => h3 (Nat.mem_primeFactors.mpr ⟨Nat.prime_three, hd, h.ne_zero⟩))
    omega
  have H := holds_root3_seven h h7 h3 (by
    intro q hq hq3
    have hqp := Nat.prime_of_mem_primeFactors hq
    have hqN := Nat.dvd_of_mem_primeFactors hq
    have hq2 : q ≠ 2 := fun e => h.not_two_dvd (e ▸ hqN)
    have := hqp.two_le
    by_contra hle
    interval_cases q <;> simp_all <;> norm_num at hqp)
  exact OmegaSevenFiveSeven.closed_no_five_seven N H

end OddPerfect

#print axioms OddPerfect.OmegaSevenFiveSeven.closed_3_11
#print axioms OddPerfect.OmegaSevenFiveSeven.closed_3_13
#print axioms OddPerfect.OmegaSevenFiveSeven.closed_3_17
#print axioms OddPerfect.OmegaSevenFiveSeven.closed_3_19
#print axioms OddPerfect.OmegaSevenFiveSeven.closed_no_five_seven
#print axioms OddPerfect.five_or_seven_dvd_of_card_primeFactors_eq_seven
'''

txt = HEAD % total + '\n'.join(g.out) + '\n' + TAIL
open(os.path.join(out, 'OmegaSevenFiveSeven.lean'), 'w').write(txt)
print('mirror nodes', total, 'theorems', len(g.out))
