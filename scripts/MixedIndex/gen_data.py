"""Generate OddPerfect/MixedIndexData.lean from cert.json (no factoring of tree values).
Before writing, the tree is checked by a Python mirror of `MixedIndex.chk` (the Lean rules:
a sender of 3 or 5 is recorded by divisibility, a second sender closes).
Usage: python3 -I gen_data.py cert.json OUT.lean"""
import json, sys
from math import prod
from sympy import factorint, isprime

T = 100  # primes below T: trial division in Lean; others: Pratt entries


def geom(p, a):
    return sum(p ** i for i in range(a + 1))


def conv(t):
    """cert.json tree -> nested tuples mirroring Lean `Tr`."""
    if 'close' in t:
        return ('abund', [tuple(x) for x in t['set']])
    p = t['p']
    ch = []
    for k in (3, 5, 7):
        c = t['br'][str(k)]
        if 'close' in c:
            ch.append(('shut', p, k))
        else:
            ch.append(('force', p, k, c['force'], conv(c['next'])))
    return ('node', p, *ch)


def is_at(p, k, t):
    return t[0] in ('force', 'shut') and t[1] == p and t[2] == k


def pPow(l):
    r = 1
    for p, e in l:
        r *= p ** e
    return r


def pSig(l):
    r = 1
    for p, e in l:
        r *= geom(p, e)
    return r


def chk(P, K, I, a3, a5, t):
    if t[0] == 'abund':
        l = t[1]
        ok = all(x[0] in K and (x[1] <= 2 or any(y[0] == x[0] and x[1] + 1 <= y[1] for y in I))
                 for x in l)
        fs = [x[0] for x in l]
        L = [(3, 2), (5, 1)] + l
        return ok and len(set(fs)) == len(fs) and 2 * pPow(L) < pSig(L)
    if t[0] == 'node':
        _, p, c3, c5, c7 = t
        return (p in K and is_at(p, 3, c3) and is_at(p, 5, c5) and is_at(p, 7, c7) and
                chk(P, K, I, a3, a5, c3) and chk(P, K, I, a3, a5, c5) and chk(P, K, I, a3, a5, c7))
    if t[0] == 'force':
        _, p, k, rs, nxt = t
        f = geom(p, k - 1)
        return ((f % 3 != 0 or a3 == 0) and (f % 5 != 0 or a5 == 0) and
                all(r in P and r not in (2, 3, 5) and f % r == 0 for r in rs) and
                nxt[0] not in ('force', 'shut') and
                chk(P, rs + K, [(p, k)] + I, p if f % 3 == 0 else a3, p if f % 5 == 0 else a5, nxt))
    _, p, k = t
    f = geom(p, k - 1)
    return f % 7 == 0 or (f % 3 == 0 and a3 != 0 and a3 != p) or (f % 5 == 0 and a5 != 0 and a5 != p)


def primes_of(t, acc):
    if t[0] == 'abund':
        return
    if t[0] == 'node':
        for c in t[2:]:
            primes_of(c, acc)
    elif t[0] == 'force':
        acc.update(t[3]); primes_of(t[4], acc)


def lean(t):
    if t[0] == 'abund':
        return '(abund [%s])' % ', '.join('(%d, %d)' % x for x in t[1])
    if t[0] == 'node':
        return '(node %d %s %s %s)' % (t[1], lean(t[2]), lean(t[3]), lean(t[4]))
    if t[0] == 'force':
        return '(force %d %d [%s] %s)' % (t[1], t[2], ', '.join(map(str, t[3])), lean(t[4]))
    return '(shut %d %d)' % (t[1], t[2])


def pratt(primes):
    """Flat Pratt entries (p, a, prime factors of p - 1 with multiplicity), smallest first."""
    need = set()

    def add(p):
        if p < T or p in need:
            return
        need.add(p)
        for q in factorint(p - 1):
            add(q)
    for p in primes:
        add(p)
    out = []
    for p in sorted(need):
        f = factorint(p - 1)
        fs = [q for q in sorted(f) for _ in range(f[q])]
        a = 2
        while not (pow(a, p - 1, p) == 1 and all(pow(a, (p - 1) // q, p) != 1 for q in f)):
            a += 1
        out.append((p, a, fs))
    return out


HEAD = '''import OddPerfect.MixedIndexCheck

/-!
# The mixed index family 3, 5, 7 with special prime 5: tree data

Generated by the script `gen_data.py` from the certificate `cert.json`. The
tree `tree` is accepted by `MixedIndex.chk` from the root state `[13]`: the prime `13` divides
`N` because `σ(3 ^ 2) = 13`. The list `primes` holds every forced prime of the tree; each is
certified by trial division below 100 and by the Pratt certificate `pcert` otherwise.
-/

namespace OddPerfect

namespace MixedIndex

open Tr

/-- The forced primes of the tree. -/
def primes : List ℕ :=
  [%s]

/-- Pratt certificate entries `(p, a, prime factors of p - 1)` for the primes at least 100. -/
def pcert : List (ℕ × ℕ × List ℕ) :=
  [%s]

/-- A prime by trial division below 100, or by an entry of `pcert`. -/
def primeB (t : ℕ) : Bool :=
  (decide (t < 100) && Pratt.trialPrime t) || (pcert.map Prod.fst).contains t

/-- The Pratt certificate is accepted. -/
theorem pcert_ok : Pratt.check pcert = true := by decide +kernel

/-- Every forced prime passes `primeB`. -/
theorem primes_ok : primes.all primeB = true := by decide +kernel

/-- Every forced prime is prime. -/
theorem primes_prime : ∀ t ∈ primes, t.Prime := by
  intro t ht
  have h := List.all_eq_true.mp primes_ok t ht
  simp only [primeB, Bool.or_eq_true, Bool.and_eq_true, decide_eq_true_eq,
    List.contains_iff_mem, List.mem_map] at h
  rcases h with ⟨_, h⟩ | ⟨e, he, rfl⟩
  · exact Pratt.trialPrime_sound h
  · exact Pratt.check_sound pcert_ok e he

/-- The exclusion tree. -/
def tree : Tr :=
  %s

/-- The tree is accepted from the root state. -/
theorem tree_ok : chk primes [13] [] 0 0 tree = true := by decide +kernel

end MixedIndex

end OddPerfect

#print axioms OddPerfect.MixedIndex.pcert_ok
#print axioms OddPerfect.MixedIndex.primes_ok
#print axioms OddPerfect.MixedIndex.primes_prime
#print axioms OddPerfect.MixedIndex.tree_ok
'''

if __name__ == '__main__':
    sys.setrecursionlimit(20000)
    t = conv(json.load(open(sys.argv[1])))
    acc = set()
    primes_of(t, acc)
    P = sorted(acc | {13})
    assert all(isprime(p) and p < 2 ** 64 for p in P)
    assert chk(set(P), [13], [], 0, 0, t), 'mirror rejects the tree'
    pc = pratt(P)
    for p, a, fs in pc:  # mirror of Pratt.checkEntry
        assert prod(fs) == p - 1 and pow(a, p - 1, p) == 1
    body = HEAD % (', '.join(map(str, P)),
                   ',\n   '.join('(%d, %d, [%s])' % (p, a, ', '.join(map(str, fs))) for p, a, fs in pc),
                   lean(t))
    open(sys.argv[2], 'w').write(body)
    print('primes', len(P), 'pratt entries', len(pc), 'bytes', len(body))
