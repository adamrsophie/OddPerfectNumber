"""Generate OddPerfect/MixedIndexTwoData.lean from the certificates cert_<tag>.json.
Each tree is first checked by a Python mirror of `MixedIndexTwo.chk2`.
Usage: python3 -I gen2.py OUT.lean TAG [TAG ...]   (tags with files cfg_<tag>.json, cert_<tag>.json)"""
import json, sys, os
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'MixedIndex'))
from gen_data import conv, is_at, pPow, pSig, geom, primes_of, lean, pratt


def chk2(P, B, c3, c5, K, I, a3, a5, t):
    if t[0] == 'abund':
        l = t[1]
        ok = all(x[0] in K and (x[1] <= 2 or any(y[0] == x[0] and x[1] + 1 <= y[1] for y in I))
                 for x in l)
        L = B + l
        fs = [x[0] for x in L]
        return ok and len(set(fs)) == len(fs) and 2 * pPow(L) < pSig(L)
    if t[0] == 'node':
        _, p, t3, t5, t7 = t
        return (p in K and is_at(p, 3, t3) and is_at(p, 5, t5) and is_at(p, 7, t7) and
                all(chk2(P, B, c3, c5, K, I, a3, a5, c) for c in (t3, t5, t7)))
    if t[0] == 'force':
        _, p, k, rs, nxt = t
        f = geom(p, k - 1)
        return (all(r in P and r not in (2, 3, 5) and f % r == 0 for r in rs) and
                nxt[0] not in ('force', 'shut') and
                chk2(P, B, c3, c5, rs + K, [(p, k)] + I, p if f % 3 == 0 else a3,
                     p if f % 5 == 0 else a5, nxt))
    _, p, k = t
    f = geom(p, k - 1)
    return (f % 7 == 0 or (c3 and f % 3 == 0 and a3 != 0 and a3 != p) or
            (c5 and f % 5 == 0 and a5 != 0 and a5 != p))


def conv_any(c):
    return ('abund', [tuple(x) for x in c['set']]) if 'close' in c else conv(c)


HEAD = '''import OddPerfect.MixedIndexTwoCheck

/-!
# The mixed index family 3, 5, 7 with special prime 5: tree data for the general case

Generated by the script `gen2.py` from the certificates `cert_<tag>.json`. Each tree is accepted
by `MixedIndexTwo.chk2` from its root data. The list `primes` holds every forced prime of the
trees; each is certified by trial division below 100 and by the Pratt certificate `pcert`
otherwise.
-/

namespace OddPerfect

namespace MixedIndexTwo

open MixedIndex.Tr

/-- The forced primes of the trees. -/
def primes : List ℕ :=
  [%s]

/-- Pratt certificate entries `(p, a, prime factors of p - 1)` for the primes at least 100. -/
def pcert : List (ℕ × ℕ × List ℕ) :=
  [%s]

/-- A prime by trial division below 100, or by an entry of `pcert`. -/
def primeB (t : ℕ) : Bool :=
  (decide (t < 100) && Pratt.trialPrime t) || (pcert.map Prod.fst).contains t

/-- The Pratt certificate is accepted. -/
theorem pcert_ok : Pratt.check pcert = true := by decide +kernel

/-- Every forced prime passes `primeB`. -/
theorem primes_ok : primes.all primeB = true := by decide +kernel

/-- Every forced prime is prime. -/
theorem primes_prime : ∀ t ∈ primes, t.Prime := by
  intro t ht
  have h := List.all_eq_true.mp primes_ok t ht
  simp only [primeB, Bool.or_eq_true, Bool.and_eq_true, decide_eq_true_eq,
    List.contains_iff_mem, List.mem_map] at h
  rcases h with ⟨_, h⟩ | ⟨e, he, rfl⟩
  · exact Pratt.trialPrime_sound h
  · exact Pratt.check_sound pcert_ok e he
%s
end MixedIndexTwo

end OddPerfect

#print axioms OddPerfect.MixedIndexTwo.pcert_ok
#print axioms OddPerfect.MixedIndexTwo.primes_ok
#print axioms OddPerfect.MixedIndexTwo.primes_prime
%s'''

TREE = '''
/-- The tree for the root `%s`: abundant base `%s`, capacity at 3 %s, capacity at 5 %s,
root primes `%s`. -/
def tree_%s : MixedIndex.Tr :=
  %s

/-- The tree `tree_%s` is accepted. -/
theorem ok_%s : chk2 primes [%s] %s %s [%s] [] 0 0 tree_%s = true := by decide +kernel
'''

if __name__ == '__main__':
    sys.setrecursionlimit(20000)
    out, tags = sys.argv[1], sys.argv[2:]
    trees, acc = [], set()
    for tag in tags:
        cfg = json.load(open('cfg_%s.json' % tag))
        t = conv_any(json.load(open('cert_%s.json' % tag)))
        trees.append((tag, cfg, t))
        primes_of(t, acc)
        acc |= set(cfg['pend'])
    P = sorted(acc)
    from sympy import isprime
    assert all(isprime(p) and p < 2 ** 64 for p in P)
    blocks, prints = [], []
    for tag, cfg, t in trees:
        B = [tuple(x) for x in cfg['base']]
        c3, c5 = cfg['cap3'] is not None, cfg['cap5'] is not None
        assert chk2(set(P), B, c3, c5, list(cfg['pend']), [], 0, 0, t), tag
        bl = lambda b: 'true' if b else 'false'
        blocks.append(TREE % (tag, B, 'on' if c3 else 'off', 'on' if c5 else 'off', cfg['pend'],
                              tag, lean(t), tag, tag, ', '.join('(%d, %d)' % x for x in B),
                              bl(c3), bl(c5), ', '.join(map(str, cfg['pend'])), tag))
        prints.append('#print axioms OddPerfect.MixedIndexTwo.ok_%s\n' % tag)
    pc = pratt(P)
    body = HEAD % (', '.join(map(str, P)),
                   ',\n   '.join('(%d, %d, [%s])' % (p, a, ', '.join(map(str, fs))) for p, a, fs in pc),
                   ''.join(blocks), ''.join(prints))
    open(out, 'w').write(body)
    print('primes', len(P), 'pratt entries', len(pc), 'bytes', len(body))
